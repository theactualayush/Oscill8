def test_expand_strategy_set_composite_labels_reach_every_rolled_instance(repo):
    composite = _composite()
    combinations = resolve_composite_combinations(composite, repo)
    labels = composite_labels_by_definition_id(combinations)
    assert sorted(labels.values()) == sorted(_names(combinations))

