def test_expand_strategy_set_rolls_composite_combinations(repo):
    composite = _composite()
    instances = expand_strategy_set(composite, _START, _END, repository=repo)

    assert instances
    assert all(isinstance(i, IntermarketStrategyInstance) for i in instances)
    # Every instance came from one of the four composed definitions --
    # rolled by Module 9's own generate_intermarket_instances(), not by
    # any second engine.
    combinations = resolve_composite_combinations(composite, repo)
    expected = [
        instance
        for combination in combinations
        for instance in generate_intermarket_instances(combination.definition, _START, _END)
    ]
    assert [i.rics for i in instances] == [i.rics for i in expected]


