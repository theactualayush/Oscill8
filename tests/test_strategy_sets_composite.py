"""
tests/test_strategy_sets_composite.py

Phase 2 of the composite ("Group A x Group B") Strategy Set design:
strategy_sets/composite.py's resolution/composition layer, and its
wiring into the real strategy_sets.expansion.expand_strategy_set()
entry point.

Real objects throughout -- real StrategyDefinition/IntermarketDefinition
shapes, a real StrategySetRepository backed by tmp_path (never
data/strategy_sets/, which is live user data), and REAL contract RIC
generation via core.futures_calendar (pure calendar arithmetic, no I/O,
no LSEG/database), mirroring tests/test_strategy_sets_expansion.py's own
approach. Nothing here fakes the strategy model or re-implements
Module 9's rolling logic.

The worked example throughout is the design brief's own:

    Group A = "STIR Flys"  selected [SR3 Fly, SON Fly]
    Group B = "Other Flys" selected [SR3 Fly, CRA Fly]

    -> (SR3 Fly - SR3 Fly: structurally zero, dropped -- Phase 3)
       SR3 Fly - CRA Fly, SON Fly - SR3 Fly, SON Fly - CRA Fly

Phase 3 note: "SR3 Fly - SR3 Fly" is still GENERATED by the Cartesian
pairing (a strategy may legitimately be selected on both sides, and the
pair still consumes its slot in the unordered-pair dedup) but is then
dropped by strategy_sets.composite.is_structurally_zero() before it is
returned, because every leg cancels. The structural-zero rule has its
own focused coverage in tests/test_strategy_sets_composite_structural_
zero.py; the tests here assert the resulting combination lists.
"""

