def _composite(
    name="Combos",
    a_source="STIR Flys",
    a_selected=("SR3 Fly", "SON Fly"),
    b_source="Other Flys",
    b_selected=("SR3 Fly", "CRA Fly"),
    entries=(),
    intermarket_entries=(),
) -> StrategySet:
    group_b = (
        None if b_source is None
        else StrategyGroup(source_set_name=b_source, selected_entry_names=b_selected)
    )
    return StrategySet(
        name=name,
        entries=entries,
        intermarket_entries=intermarket_entries,
        groups=StrategyGroupPair(
            group_a=StrategyGroup(source_set_name=a_source, selected_entry_names=a_selected),
            group_b=group_b,
        ),
    )


def _names(combinations) -> list[str]:
    return [c.name for c in combinations]


