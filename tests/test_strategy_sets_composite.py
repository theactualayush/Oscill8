def test_group_b_legs_are_negated_so_a_minus_a_is_structurally_zero(repo):
    # Composition is unchanged by Phase 3 -- checked directly, since the
    # resulting combination is (correctly) no longer returned.
    definition = compose_definition(
        SourceStrategy("STIR Flys", "SR3 Fly", _fly("SOFR")),
        SourceStrategy("Other Flys", "SR3 Fly", _fly("SOFR")),
    )
    by_offset: dict[int, float] = {}
    for leg in definition.legs:
        by_offset[leg.offset] = by_offset.get(leg.offset, 0.0) + leg.weight
    assert set(by_offset.values()) == {0.0}


